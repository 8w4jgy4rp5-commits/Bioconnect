// Builds the itch.io HTML5 upload: node tools/build-itch.cjs → dist/bioconnect-itch.zip
// The live site files are never edited; only the copies in dist/itch/ are rewritten.
// itch.io runs the game inside an iframe, where Stripe checkout and Google sign-in
// cannot work, so this build has no store, revivals or sign-in, and points to the official site.
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const out = path.join(root, 'dist', 'itch');
const zip = path.join(root, 'dist', 'bioconnect-itch.zip');
const site = 'https://bioconnectpazzle.com/';

const files = [
  'index.html', 'favicon.ico', 'apple-touch-icon.png', 'site.webmanifest',
  'style.css', 'pop.css', 'eldritch.css', 'feedback.css', 'onboarding.css',
  'audio-synth.js', 'audio.js', 'monetization.js', 'script.js', 'watch.js', 'skin.js',
  'shared/app-footer.css', 'shared/app-sync.js', 'shared/lang-detect.js', 'shared/supabase-config.js',
  'audio/applause-02.mp3', 'audio/cheer-crowd01-6.mp3'
];
const dirs = ['img']; // copied whole, except img/ref (concept references, not loaded by the game)

fs.rmSync(out, { recursive: true, force: true });
fs.rmSync(zip, { force: true });
for (const f of files) {
  fs.mkdirSync(path.dirname(path.join(out, f)), { recursive: true });
  fs.copyFileSync(path.join(root, f), path.join(out, f));
}
for (const d of dirs) {
  fs.cpSync(path.join(root, d), path.join(out, d), { recursive: true, filter: src => !src.includes(path.join('img', 'ref')) });
}

fs.writeFileSync(path.join(out, 'shared/monetization-config.js'), `// itch.io build: no store, payments or ads (generated by tools/build-itch.cjs).
window.BioMonetizationConfig = Object.freeze({
  storeEnabled: false,
  paymentsEnabled: false,
  adsEnabled: false,
  adClient: '',
  adTestMode: true
});
`);

// Every rewrite must match exactly, so a changed index.html fails the build instead of shipping silently.
let html = fs.readFileSync(path.join(out, 'index.html'), 'utf8');
function swap(pattern, replacement, label) {
  const before = html;
  html = html.replace(pattern, replacement);
  if (html === before) throw new Error('index.html rewrite did not match: ' + label);
}
swap(/<!-- cobbleworks:analytics:start -->[\s\S]*?<!-- cobbleworks:analytics:end -->/, '', 'analytics beacon');
swap(/href="legal\//g, `href="${site}legal/`, 'legal links');
swap('(and synced when you are logged in)', `(on itch.io it stays on this device)`, 'footer note');
swap(/<!-- cobbleworks:footer:start -->[\s\S]*?<!-- cobbleworks:footer:end -->/,
  `<footer class="cw-footer">
    <a href="${site}" target="_blank" rel="noopener noreferrer">Official site: bioconnectpazzle.com</a>
  </footer>`, 'site footer');
fs.writeFileSync(path.join(out, 'index.html'), html);

// Windows tar writes zip entries with forward slashes (Compress-Archive in PowerShell 5.1 does not).
const tar = process.platform === 'win32' ? path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe') : 'zip';
// List top-level entries (not '.') so index.html sits at the zip root without a './' prefix.
const entries = fs.readdirSync(out);
if (process.platform === 'win32') execFileSync(tar, ['-a', '-c', '-f', zip, '-C', out, ...entries]);
else execFileSync('zip', ['-r', '-q', zip, ...entries], { cwd: out });

const size = fs.statSync(zip).size;
console.log(`Built ${path.relative(root, zip)} (${(size / 1048576).toFixed(1)} MB)`);
