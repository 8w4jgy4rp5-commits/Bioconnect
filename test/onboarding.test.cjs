const assert=require('node:assert/strict');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const sim=require(path.join(root,'sim.js'));
sim.use();
const {ctx,state,el}=sim.G();
const run=code=>vm.runInContext(code,ctx);
ctx.location={search:''};
let stored=null;
ctx.localStorage={getItem:()=>stored,setItem:(_key,value)=>{stored=value;}};
// The DOM is intentionally absent: spy on all persistence paths while
// exercising the actual placeTile / merge / feeding / clock code.
let writes=0;
ctx.bankScore=ctx.writeBest=ctx.writeMet=ctx.recordRun=ctx.reportRunOutcome=()=>{writes++;};
ctx.replayChain=()=>{};
el.lessonNext={focus(){}};
run('lesson.active=true; state.over=false; state.paused=false; state.score=0; state.ticks=0; state.best=12345;');
const prepare=step=>run(`lesson.step=${step}; lesson.done=false; state.cells=new Array(CELLS).fill(null); for(const [at,kind] of LESSONS[${step}].tiles) state.cells[at]=makeTile(kind); state.stock=[LESSONS[${step}].hand];`);
prepare(0);
ctx.placeTile(0);
assert.equal(state.cells[0],null,'wrong square does not consume a tile');
assert.equal(state.stock.length,1);
ctx.placeTile(13);
assert.equal(state.cells[12].kind,'grass');
ctx.placeTile(14);
assert.equal(state.cells[14],null,'success locks additional placement');
prepare(1);
ctx.placeTile(10);
assert.equal(state.cells.filter(Boolean).length,1);
assert.equal(state.cells[12].kind,'fox','the suggested placement creates a real two-step chain');
prepare(2);
state.cells[12].clock=run('ANIMALS.rabbit.starveAt - 1');
ctx.placeTile(13);
assert.equal(state.cells[13],null,'the grass is eaten');
assert.equal(state.cells[12].kind,'rabbit');
assert.equal(state.cells[12].clock,0,'feeding resets hunger');
ctx.worldTick();
assert.equal(state.ticks,0,'time does not advance in practice');
assert.equal(state.score,0);
assert.equal(state.best,12345);
assert.equal(writes,0,'practice does not write scores, discoveries or outcomes');
el.lessonBar={};
run('lesson.active=false; lesson.handled=false; state.best=0; runsPlayed=0; met.clear();');
assert.equal(ctx.offerLesson(),true,'new players are offered practice');
stored='done';
assert.equal(ctx.offerLesson(),false,'completion is remembered');
stored=null;
state.best=100;
assert.equal(ctx.offerLesson(),false,'returning players with a best score are not interrupted');
state.best=0;
ctx.location.search='?watch';
assert.equal(ctx.offerLesson(),false,'bot playback is not interrupted');
ctx.location.search='?celebrate';
assert.equal(ctx.offerLesson(),false,'celebration preview is not interrupted');
ctx.location.search='';
ctx.localStorage.getItem=()=>{throw new Error('storage unavailable');};
assert.equal(ctx.offerLesson(),true,'unavailable storage does not break first play');
run('lesson.handled=true;');
assert.equal(ctx.offerLesson(),false,'storage failure cannot loop practice in the current session');
console.log('Practice checks passed: merge, chain, feeding, clock, record isolation, first-visit selection.');
