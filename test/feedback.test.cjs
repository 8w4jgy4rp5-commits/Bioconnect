const assert=require('node:assert/strict');
const path=require('node:path');
const sim=require('../sim.js');
sim.use();
const {ctx,state,el,ANIMALS}=sim.G();
ctx.newGame();
assert.deepEqual(JSON.parse(JSON.stringify(state.runStats)),{placed:0,maxChain:0,starved:0,cleared:0,meals:0});
state.cells.fill(null);
state.cells[11]=ctx.makeTile('grass');state.cells[12]=ctx.makeTile('rabbit');
state.cells[6]=ctx.makeTile('stone');state.cells[7]=ctx.makeTile('bones');state.cells[17]=ctx.makeTile('scrub');
state.stock=['grass','sprout','grass'];state.next='grass';state.topKind='rabbit';
const before=JSON.stringify(state);
const forecast=ctx.previewGrowth(10);
assert.equal(JSON.stringify(state),before,'preview must not mutate the board or counters');
const clearings=Array.from(ctx.growthClearings(forecast)).sort((a,b)=>a-b);
assert.deepEqual(clearings,[6,7,17],'predicts first-merge and later-chain removals of all three blocker kinds');
ctx.placeTile(10);
assert.equal(state.runStats.placed,1);assert.equal(state.runStats.maxChain,2);assert.equal(state.runStats.cleared,3);
for(const at of clearings)assert.equal(state.cells[at],null,'prediction matches the actual placement');
assert.equal(state.cells[12].kind,'fox');
assert.deepEqual(Array.from(ctx.readRunStats(state.runStats).chainKinds),['grass','rabbit','fox']);
const prior=JSON.stringify(state.runStats);
ctx.placeTile(12);
assert.equal(JSON.stringify(state.runStats),prior,'a rejected placement is not counted');
state.cells.fill(null);state.cells[12]=ctx.makeTile('rabbit');state.cells[12].clock=ANIMALS.rabbit.starveAt-1;
ctx.worldTick();
assert.equal(state.runStats.starved,1,'actual starvation increments the run counter');
assert.equal(ctx.readRunStats(state.runStats).lostKind,'rabbit');
const invalidVisual={...state.runStats,chainKinds:['grass','tiger','fox']};
assert.equal(ctx.readRunStats(invalidVisual).chainKinds,undefined,'invalid or invented growth paths are discarded');
state.cells.fill(null);state.cells[12]=ctx.makeTile('rabbit');state.cells[12].clock=ANIMALS.rabbit.eatAt-1;state.cells[13]=ctx.makeTile('grass');
ctx.worldTick();
assert.equal(state.runStats.meals,1);assert.equal(state.runStats.starved,1,'eating is separate from starvation');
const recap=ctx.runRecap(state.runStats);
assert.equal(recap.fact,'Great chain! Keep the next match nearby.','a big chain outranks one hungry animal');
assert.ok(recap.fact.length < 60,'recap stays a single short comment');
const fact=o=>ctx.runRecap({placed:9,maxChain:0,starved:0,cleared:0,meals:0,...o}).fact;
assert.equal(fact({cleared:1,starved:5}),'Nice clearing! Line up the next pair.');
assert.equal(fact({maxChain:1,starved:1,meals:1}),'Almost! Try setting up a two-step chain.','starving no more than eating is not the headline');
assert.equal(fact({maxChain:1,starved:3,meals:2}),'So close! Leave a little room for food.');
const beforeRevival=JSON.stringify(state.runStats);
state.over=true;
assert.equal(ctx.reviveRun(),true);
assert.equal(JSON.stringify(state.runStats),beforeRevival,'a revival continues the same run counters');
assert.equal(ctx.runRecap(null),null,'old records do not invent counters');
assert.equal(ctx.readRunStats({placed:-1,maxChain:2,cleared:0,starved:0,meals:0}),null);
el.startScreen={hidden:true};ctx.document.body={classList:{toggle(){},remove(){},add(){}}};
const saved=ctx.snapshotRun();
assert.equal(saved.runStats.starved,1);
saved.runStats.starved=7;
assert.equal(state.runStats.starved,1,'snapshot counters are copied');
ctx.restoreRun(saved);assert.equal(state.runStats.starved,7);
delete saved.runStats;ctx.restoreRun(saved);
assert.equal(state.runStats,null,'old snapshots never reuse another run\'s counters');
ctx.newGame();assert.equal(state.runStats.placed,0);assert.equal(state.runStats.starved,0);
state.cells.fill(null);state.cells[0]=ctx.makeTile('stone');state.cells[1]=ctx.makeTile('grass');state.cells[2]=ctx.makeTile('rabbit');
assert.deepEqual(Array.from(ctx.growthClearings([{bones:[0,0],trampled:[0,1,2]}])),[0],'elephant footprints count actual blockers once, not plants or animals');
console.log('Feedback checks passed: preview/placement parity, counters, recap, reset, and old/new snapshots.');
