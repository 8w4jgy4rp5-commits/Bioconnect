assert.equal(r.fact,'So close! One more lion makes a tiger.','the next discovery one merge away is named');
assert.equal(r.tip,'Build the next lion right beside this one.');
r=pick({starved:2,starvedBy:{bear:2,rabbit:1}},{cells:board([]),topKind:'bear'});
assert.equal(r.fact,'2 bears starved.');
assert.equal(r.tip,'Bears eat grass, rabbits and deer. Keep food beside them.','diet comes from the rules');
