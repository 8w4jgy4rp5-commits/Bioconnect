assert.equal(r.fact,'Great chain! 4 steps, sprout → deer.');
r=pick({cleared:4});assert.equal(r.fact,'Nice clearing! You cracked 4 blockers.');
const RV=require('vm').runInContext('RULES_VERSION',ctx);
