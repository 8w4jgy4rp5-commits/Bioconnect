assert.equal(JSON.stringify(state.runStats),prior,'a rejected placement is not counted');
state.cells.fill(null);state.cells[12]=ctx.makeTile('rabbit');state.cells[12].clock=ANIMALS.rabbit.starveAt-1;
ctx.worldTick();
assert.equal(state.runStats.starved,1,'actual starvation increments the run counter');
assert.equal(ctx.readRunStats(state.runStats).lostKind,'rabbit');
const invalidVisual={...state.runStats,chainKinds:['grass','tiger','fox']};
assert.equal(ctx.readRunStats(invalidVisual).chainKinds,undefined,'invalid or invented growth paths are discarded');
